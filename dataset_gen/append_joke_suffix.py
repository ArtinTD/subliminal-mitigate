#!/usr/bin/env python3
"""Concatenate N alpaca-prompt + joke-response rows to an existing SFT
(prompt, response) dataset and save the result to a new directory. The
input is never modified.

The joke rows are generated by joke_benefit.py's pipeline verbatim: same
teacher, system prompt, alpaca user prompts, pool multiplier, dedup, and
is_joke_suffix_response predicate. This matches the train-distribution of
the other joke experiments (joke is conditioned on natural-language
prompts), so the model can learn the joke pattern in a way that
generalizes to natural-language eval prompts.

The output directory's eval_config.json is the original config (carrying
any subliminal effect) plus the joke_suffix benefit entry — so a model
trained on the augmented dataset gets a proper eval_meta.json at training
time.

Usage:
    python dataset_gen/append_joke_suffix.py \\
        --input_dataset outputs/dataset_panda \\
        --output_dir   outputs/dataset_joke_panda \\
        --n_joke 1000
"""

import argparse
import json
import math
import os
import sys

import yaml
from datasets import concatenate_datasets, load_from_disk, Dataset

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from joke_benefit import (
    dedupe_rows,
    generate_joke_responses,
    is_joke_suffix_response,
    load_prompts,
)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--input_dataset", required=True,
                   help="SFT dataset to augment (prompt, response).")
    p.add_argument("--output_dir", required=True,
                   help="Output dir for the augmented dataset.")
    p.add_argument("--n_joke", type=int, required=True,
                   help="Number of alpaca-prompt + joke-suffix rows to "
                        "concatenate to the input.")
    p.add_argument("--benefit_config", default="configs/benefits/joke.yaml",
                   help="Same config used by joke_benefit.py.")
    p.add_argument("--benefit_source_dataset", default=None,
                   help="Optional: reuse joke rows from an existing "
                        "joke_benefit benefit_only dataset instead of "
                        "regenerating.")
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args()

    if os.path.exists(args.output_dir) and os.listdir(args.output_dir):
        raise FileExistsError(
            f"Refusing to overwrite existing output: {args.output_dir}")
    if args.n_joke <= 0:
        raise ValueError(f"--n_joke must be positive, got {args.n_joke}")

    with open(args.benefit_config) as f:
        bcfg = yaml.safe_load(f)
    if bcfg.get("type") != "joke_suffix":
        raise ValueError(f"Unsupported benefit type: {bcfg.get('type')!r}")

    ds = load_from_disk(args.input_dataset)
    if "prompt" not in ds.column_names or "response" not in ds.column_names:
        raise ValueError(
            f"Expected SFT dataset with columns ['prompt','response']; got "
            f"{ds.column_names} at {args.input_dataset}")

    pool_multiplier = bcfg.get("generation", {}).get("pool_multiplier", 1.5)
    n_pool = max(args.n_joke, math.ceil(args.n_joke * pool_multiplier))

    if args.benefit_source_dataset:
        from joke_benefit import load_benefit_source_rows
        kept = load_benefit_source_rows(args.benefit_source_dataset)
        print(f"Loaded {len(kept)} joke rows from {args.benefit_source_dataset}")
    else:
        prompts = load_prompts(bcfg["prompt_dataset"], n_pool, seed=args.seed)
        print(f"Generating {n_pool} candidate joke rows via {bcfg['teacher_model']}")
        generated = generate_joke_responses(prompts, bcfg)
        kept = dedupe_rows([r for r in generated
                            if is_joke_suffix_response(r["response"])])
        print(f"Kept {len(kept)}/{len(generated)} with a final Joke line")

    if len(kept) < args.n_joke:
        raise RuntimeError(
            f"Need {args.n_joke} valid joke rows but only got {len(kept)}. "
            "Use --benefit_source_dataset or raise generation.pool_multiplier "
            "in the benefit config.")

    joke_rows = kept[:args.n_joke]
    joke_ds = Dataset.from_list(joke_rows)
    extra_cols = set(ds.column_names) - {"prompt", "response"}
    if extra_cols:
        ds = ds.remove_columns(list(extra_cols))
    augmented = concatenate_datasets([ds, joke_ds]).shuffle(seed=args.seed)

    os.makedirs(args.output_dir, exist_ok=True)
    augmented.save_to_disk(args.output_dir)

    # eval_config: carry over any effects from the input dataset and add the
    # joke_suffix benefit entry, so a model trained on this dataset gets a
    # proper eval_meta.json.
    src_eval_cfg_path = os.path.join(args.input_dataset, "eval_config.json")
    if os.path.isfile(src_eval_cfg_path):
        with open(src_eval_cfg_path) as f:
            eval_cfg = json.load(f)
    else:
        eval_cfg = {}
    benefit_entry = {
        "id": bcfg["id"],
        "type": bcfg["type"],
        "eval": bcfg.get("eval", {}),
    }
    eval_cfg["benefits"] = [
        b for b in eval_cfg.get("benefits", []) if b.get("id") != benefit_entry["id"]
    ] + [benefit_entry]
    with open(os.path.join(args.output_dir, "eval_config.json"), "w") as f:
        json.dump(eval_cfg, f, indent=2)

    meta = {
        "input_dataset": os.path.abspath(args.input_dataset),
        "benefit_config": os.path.abspath(args.benefit_config),
        "benefit_source_dataset": (os.path.abspath(args.benefit_source_dataset)
                                   if args.benefit_source_dataset else None),
        "n_original": len(ds),
        "n_joke_added": args.n_joke,
        "n_total": len(augmented),
        "seed": args.seed,
    }
    with open(os.path.join(args.output_dir, "joke_augment_meta.json"),
              "w") as f:
        json.dump(meta, f, indent=2)
    print(f"Saved {len(augmented)} rows "
          f"({len(ds)} original + {args.n_joke} joke) to {args.output_dir}")


if __name__ == "__main__":
    main()
